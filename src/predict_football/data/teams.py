class TeamResolver:
    """Resolves source-specific team spellings to canonical identities.

    Built once at import and reused; construction is cheap but not free, and it
    is read-only afterwards.

    Args:
        teams: Registry to resolve against. Defaults to :data:`TEAMS`.

    Example:
        >>> resolver = TeamResolver()
        >>> resolver.resolve("Man United")
        'Manchester United'
        >>> resolver.resolve("Manchester United")
        'Manchester United'
    """

    def __init__(self, teams: tuple[Team, ...] = TEAMS) -> None:
        self._by_key: dict[str, Team] = {}
        for team in teams:
            for name in (team.canonical_name, *team.aliases):
                self._by_key[self._key(name)] = team

    @staticmethod
    def _key(name: str) -> str:
        """Normalise a name into a lookup key.

        Args:
            name: Raw team name from any source.

        Returns:
            A comparable lowercase form with punctuation removed.
        """
        return slugify(name).replace(" fc", "").replace(" cf", "").replace(" afc", "").strip()

    def resolve(self, raw_name: str) -> str | None:
        """Resolve a source name to its canonical form.

        Args:
            raw_name: Team name exactly as the source published it.

        Returns:
            The canonical name, or ``None`` when the name is unknown. Returning
            ``None`` rather than guessing is deliberate: a wrong merge is far
            more damaging than a visible gap.
        """
        if raw_name is None:
            return None
        cleaned = normalise_whitespace(str(raw_name))
        if not cleaned:
            return None
        team = self._by_key.get(self._key(cleaned))
        return team.canonical_name if team else None

    def resolve_or_pass_through(self, raw_name: str) -> str:
        """Resolve a name, falling back to the tidied original when unknown.

        Used on ingest so a new club is not silently dropped. The fact that a
        name passed through unrecognised is recorded in the database so the gap
        is visible rather than silent.

        Args:
            raw_name: Team name as published by the source.

        Returns:
            Canonical name, or whitespace-normalised original.
        """
        resolved = self.resolve(raw_name)
        if resolved is not None:
            return resolved
        tidied = normalise_whitespace(str(raw_name))
        logger.info("Unrecognised team name %r; stored as-is and flagged for review", raw_name)
        return tidied

    def is_known(self, raw_name: str) -> bool:
        """Report whether a name resolves to a registered team.

        Args:
            raw_name: Team name as published by a source.

        Returns:
            True if the name is in the registry.
        """
        return self.resolve(raw_name) is not None

    def team_id(self, raw_name: str) -> str:
        """Return the canonical team identifier for a source name.

        Args:
            raw_name: Team name as published by a source.

        Returns:
            Slug identifier for the resolved or tidied team.
        """
        return make_team_id(self.resolve_or_pass_through(raw_name))

    def __len__(self) -> int:
        return len(self._by_key)

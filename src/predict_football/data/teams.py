"""Canonical team names and cross-provider name resolution.

Different sources spell the same club differently: football-data.co.uk writes
"Man United", StatsBomb writes "Manchester United", and neither matches the club's
own preferred styling ("Manchester United FC"). Modelling treats those as three
different teams, which quietly corrupts every rating.

The registry below pins one canonical name per club. Aliases are explicit and
hand-checked rather than generated by fuzzy matching, because automatic fuzzy
matching on a list of 20 team names will eventually merge two clubs that share a
word -- and a silent merge is much harder to notice than a missing alias.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field

from predict_football.data.identifiers import make_team_id, normalise_whitespace, slugify

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class Team:
    """A club or national team with its canonical identity.

    Attributes:
        canonical_name: The single name used everywhere in this project.
        aliases: Known alternative spellings from other sources. Keys and values
            are compared after slugification.
        league_keys: Competitions this team appears in.
        short_name: Common short form, used in the UI and narrative text.
        country: Governing country, where meaningful.
    """

    canonical_name: str
    aliases: tuple[str, ...] = field(default_factory=tuple)
    league_keys: tuple[str, ...] = field(default_factory=tuple)
    short_name: str | None = None
    country: str | None = None

    @property
    def team_id(self) -> str:
        """Stable identifier derived from the canonical name."""
        return make_team_id(self.canonical_name)


